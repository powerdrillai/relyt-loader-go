func (p *BulkProcessor) SaveBufferToFileAndGenerateTask(currentBuffer *Buffer, toAuxFile bool) error {
	Debug("Buffer %s is full (records: %d), switching buffers",
		currentBuffer.ID, currentBuffer.GetRecordCount())

	// deduplicate records
	deletedRecords, deletedGroupRecords, versionMap := currentBuffer.DeduplicateRecords(len(p.pkColumns) > 0, p.versionColIndex >= 0, p.config.DeleteBeforeInsert)

	columnNames := GetColumnNames(p.fields)

	taskImportStrategy := p.config.ImportStrategy

	if err := currentBuffer.BufferWriteToFile(columnNames, p.s3Client, p.config.TuplesPrePartition, taskImportStrategy == CopyFromS3); err != nil {
		// if import strategy is CopyFromS3, and upload buffer to s3 failed, try to use InsertOnConflict
		if strings.Contains(err.Error(), "Upload buffer to s3 failed") {
			if taskImportStrategy == CopyFromS3 {
				Debug("%v, fallback to InsertOnConflict", err)
				taskImportStrategy = InsertOnConflict
			}
		} else {
			return err
		}
	}

	// mark Flushed BEFORE enqueueing: a fail-fast consumer may set a terminal
	// status immediately, and a later Flushed write would resurrect the buffer
	p.bufferManager.SetBufferStatus(currentBuffer.ID, BufferStatusFlushed)

	// create task and send to task queue without becoming permanently blocked
	// after the importer exits during shutdown.
	task := NewBufferTask(currentBuffer, deletedRecords, deletedGroupRecords, versionMap, taskImportStrategy)
	select {
	case p.bufferTaskQueue <- task:
	case <-p.ctx.Done():
		return ErrProcessorClosed
	}
	// sharded mode skips the reset so AutoFlush still freezes quiet
	// instances' partial buffers while a busy instance keeps rolling over
	if !p.isSharded {
		p.setLastFlushTime(time.Now())
	}

	return nil
}

// insert threadv2 for buffer
func (p *BulkProcessor) InsertThreadV2() {
	defer p.bufferThreadWg.Done()
	defer close(p.insertV2Done)

	log.Printf("InsertThreadV2 started")

	var localRoutingInited = false
	var localRoutingHashSet map[string]struct{}

	for {
		select {
		case <-p.ctx.Done():
			log.Println("InsertThreadV2 context canceled, exiting...")
			return
		case <-p.routingQueueV2:
			p.routingMutex.Lock()
			localRoutingHashSet = p.routingHashSet
			localRoutingInited = true
			p.routingMutex.Unlock()
		case record := <-p.recordQueueV2:
			values := record.Values
			operation := record.Tag

			recordIndex := RecordIndex{
				fileID:    record.FileID,
				routingID: record.RoutingID,
			}

			if p.pkColumnsIndex != nil && operation == OperationInsert {
				record.PKValues = make([]string, len(p.pkColumnsIndex))
				for i, index := range p.pkColumnsIndex {
					record.PKValues[i] = values[index]
				}
			}

			toAuxFile := false
			if p.routingColIndex >= 0 {
				if !localRoutingInited {
					p.routingMutex.Lock()
					localRoutingHashSet = p.routingHashSet
					localRoutingInited = true
					p.routingMutex.Unlock()
				}
				if _, exists := localRoutingHashSet[record.RoutingID]; exists {
					toAuxFile = true
				}
			}

			bufKey := bufferKey("", toAuxFile)
			if p.isSharded {
				bufKey = bufferKey(record.InstanceID, false)
			}

			p.bufferManager.bufferOperationsMutex.Lock()

			currentBuffer := p.bufferManager.GetCurrentBuffer(bufKey)
			if currentBuffer == nil || !p.bufferManager.IsActive(currentBuffer.ID) {
				currentBuffer = p.bufferManager.NewBuffer(p.config.LocalFilePrefix, p.config.BufferMaxRecords, toAuxFile, record.InstanceID)
				Debug("New buffer created: %s, max records: %d", currentBuffer.ID, p.config.BufferMaxRecords)
				p.bufferManager.SetCurrentBuffer(currentBuffer, bufKey)

				targetTable := p.config.PostgreSQL.Table
				if toAuxFile {
					targetTable = p.GetAuxTableName()
				}
				pgTable := fmt.Sprintf("%s.%s", p.config.PostgreSQL.Schema, targetTable)
				localFilePath := currentBuffer.LocalFilePath
				checkpointReady := make(chan error, 1)
				currentBuffer.CheckpointReady = checkpointReady
				p.metadataWg.Add(1)
				go func() {
					defer p.metadataWg.Done()
					checkpointReady <- p.insertDeltaCheckpointUntilDone(pgTable, localFilePath)
					close(checkpointReady)
				}()
			}

			// feedback keys accumulate per buffer so error callbacks report
			// only the failing buffer's keys
			if p.feedFieldIndex >= 0 && operation == OperationInsert {
				currentBuffer.FeedbackKeys[values[p.feedFieldIndex]] = true
			}

			// check version
			if p.versionColIndex >= 0 && operation == OperationInsert {
				record.Version = values[p.versionColIndex]

				if version, exsit := currentBuffer.MaxVersionMap[recordIndex]; exsit && version > record.Version {
					p.bufferManager.bufferOperationsMutex.Unlock()
					p.recordsNum.Add(-1)
					continue
				}
				currentBuffer.MaxVersionMap[recordIndex] = record.Version
			}

			currentBuffer.AddRecord(record)
			p.recordsNum.Add(-1)

			if currentBuffer.IsFull() && p.bufferManager.IsActive(currentBuffer.ID) {
				// deactivate current buffer, create new buffer
				p.bufferManager.SetBufferStatus(currentBuffer.ID, BufferStatusFrozen)
				p.bufferManager.SetCurrentBuffer(nil, bufKey)
				p.bufferManager.bufferOperationsMutex.Unlock()

				if err := p.SaveBufferToFileAndGenerateTask(currentBuffer, toAuxFile); err != nil {
					p.bufferManager.SetBufferStatus(currentBuffer.ID, BufferStatusFlushError)
					feedbackKeysArray := currentBuffer.GetFeedbackKeys()
					feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))

					if p.config.ImportErrorCallback != nil {
						log.Printf("save file %s failed before callback: %s", currentBuffer.LocalFilePath, feedbackKeysString)
						p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
					} else {
						log.Printf("save file %s failed with no callback: %s", currentBuffer.LocalFilePath, feedbackKeysString)
					}
					continue
				}
			} else {
				p.bufferManager.bufferOperationsMutex.Unlock()
			}
		}
	}
}

func (p *BulkProcessor) ImporterThreadV2() {
	defer p.bufferThreadWg.Done()

	log.Println("BufferTask thread started")

	if p.isSharded {
		p.importShardedV2()
		return
	}

	for {
		select {
		case <-p.ctx.Done():
			log.Println("BufferTask thread context canceled, exiting...")
			return
		case task := <-p.bufferTaskQueue:

			Debug("Begin to import task: %s, records: %d", task.TaskId, task.RecordCount)

			// keys travel with the task so error callbacks report the failing
			// buffer's keys, not whatever accumulated globally
			feedbackKeysArray := task.FeedbackKeys

			if p.config.MaxConcurrentWorkers > 1 {
				for {
					currentActive := atomic.LoadInt32(&p.activeWorkers)
					if currentActive < int32(p.config.MaxConcurrentWorkers) {
						break
					}
					log.Printf("Waiting for available worker slot, current active: %d, max: %d, queue len: %d",
						currentActive, p.config.MaxConcurrentWorkers, len(p.bufferTaskQueue))
					time.Sleep(500 * time.Millisecond)
				}

				p.workerWg.Add(1)
				workerID := int(atomic.AddInt32(&p.activeWorkers, 1))

				go func(t *BufferTask, wID int) {
					defer p.workerWg.Done()
					defer atomic.AddInt32(&p.activeWorkers, -1)

					log.Printf("Parallel Worker %d started processing task: %s (records: %d)", wID, t.TaskId, t.RecordCount)
					startTime := time.Now()

					p.processBufferTask(t, wID, feedbackKeysArray)

					duration := time.Since(startTime)
					Log("Parallel Worker %d finished import: strategy is %d, processing task: %s, duration: %v", wID, t.ImportStrategy, t.TaskId, duration)
				}(task, workerID)
			} else {
				startTime := time.Now()
				p.processBufferTask(task, -1, feedbackKeysArray)
				Log("Single Worker finished import: strategy is %d, processing task: %s, records: %d, duration: %v", task.ImportStrategy, task.TaskId, task.RecordCount, time.Since(startTime))
			}
		}
	}
}

// importShardedV2 dispatches each task to a serial worker for its owning
// instance, created lazily. One worker per instance supersedes
// MaxConcurrentWorkers: parallelism is across instances, and per-instance
// order plus isolation of a down instance hold by construction. The dispatch
// never blocks on one instance's full queue: tasks for an instance that has
// been down long enough to back up 100 buffers fail fast through the error
// callback while other instances continue unaffected.
func (p *BulkProcessor) importShardedV2() {
	queues := make(map[string]chan *BufferTask)

	// drain until InsertThreadV2 has exited (so a send blocked on a full
	// bufferTaskQueue can land instead of being orphaned), then close
	// instance queues so workers finish their current task and fail the rest
	shutdown := func(cause error) {
		log.Println("BufferTask thread context canceled, exiting...")
		for waiting := true; waiting; {
			select {
			case task := <-p.bufferTaskQueue:
				p.failBufferTaskOnShutdown(task, cause)
			case <-p.insertV2Done:
				waiting = false
			}
		}
		for _, queue := range queues {
			close(queue)
		}
		p.workerWg.Wait()
		for {
			select {
			case task := <-p.bufferTaskQueue:
				p.failBufferTaskOnShutdown(task, cause)
			default:
				return
			}
		}
	}

	for {
		select {
		case <-p.ctx.Done():
			shutdown(errShutdownAbandoned())
			return
		case task := <-p.bufferTaskQueue:
			Debug("Begin to import task: %s, records: %d", task.TaskId, task.RecordCount)
			queue, ok := queues[task.InstanceID]
			if !ok {
				queue = make(chan *BufferTask, 100)
				queues[task.InstanceID] = queue
				p.workerWg.Add(1)
				go p.instanceWorker(task.InstanceID, queue)
			}
			select {
			case queue <- task:
			case <-p.ctx.Done():
				cause := errShutdownAbandoned()
				p.failBufferTaskOnShutdown(task, cause)
				shutdown(cause)
				return
			default:
				// fail fast OFF the dispatch goroutine: the checkpoint write
				// and callback must not stall dispatch for healthy instances
				p.workerWg.Add(1)
				go func(t *BufferTask, backlog int) {
					defer p.workerWg.Done()
					p.failBufferTask(t, -1, errors.Errorf(
						"instance %s import queue full (%d tasks backed up), failing task fast", t.InstanceID, backlog))
				}(task, len(queue))
			}
		}
	}
}

func errShutdownAbandoned() error {
	return errors.New("processor shutting down before task could be imported")
}

// instanceWorker serially imports one instance's tasks until its queue is
// closed. After shutdown begins, the in-flight task still finishes (imports
// run on background contexts) and the remaining queued tasks are failed.
func (p *BulkProcessor) instanceWorker(instanceID string, queue chan *BufferTask) {
	defer p.workerWg.Done()

	for task := range queue {
		select {
		case <-p.ctx.Done():
			p.failBufferTaskOnShutdown(task, errShutdownAbandoned())
			continue
		default:
		}
		startTime := time.Now()
		p.processBufferTask(task, -1, task.FeedbackKeys)
		Log("Instance %s worker finished import: strategy is %d, processing task: %s, records: %d, duration: %v",
			instanceID, task.ImportStrategy, task.TaskId, task.RecordCount, time.Since(startTime))
	}
}

// failBufferTaskOnShutdown fails a never-attempted task at shutdown:
// checkpoint marked FAILED and callback fired, but the buffer stays Flushed
// so RecycleBuffers preserves its local file and checkpoint row for recovery.
func (p *BulkProcessor) failBufferTaskOnShutdown(task *BufferTask, cause error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	if err := p.pgClient.UpdateDeltaCheckpointStatus(ctx, p.processId, []string{task.LocalFile}, CheckpointStatusFailed, -1, cause.Error()); err != nil {
		Debug("failed to update checkpoint for shutdown-abandoned file: %v\n", err)
	}
	cancel()

	feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(task.FeedbackKeys, ","))
	Error("import task %s abandoned at shutdown: %s: %v", task.TaskId, feedbackKeysString, cause)
	if p.config.ImportErrorCallback != nil {
		p.config.ImportErrorCallback(p.config.FeedbackColumn, task.FeedbackKeys, cause, p.config.CallbackResource)
	}
}

// failBufferTask is the terminal failure path for exhausted or abandoned
// tasks: checkpoint failed, buffer marked ImportError, callback fired.
func (p *BulkProcessor) failBufferTask(task *BufferTask, workerID int, cause error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	if err := p.pgClient.UpdateDeltaCheckpointStatus(ctx, p.processId, []string{task.LocalFile}, CheckpointStatusFailed, -1, cause.Error()); err != nil {
		Debug("Worker %d failed to update checkpoint for error file: %v\n", workerID, err)
	}
	cancel()

	p.bufferManager.SetBufferStatus(task.TaskId, BufferStatusImportError)
	feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(task.FeedbackKeys, ","))
	Error("Worker %d import task %s failed: %s: %v", workerID, task.TaskId, feedbackKeysString, cause)
	if p.config.ImportErrorCallback != nil {
		p.config.ImportErrorCallback(p.config.FeedbackColumn, task.FeedbackKeys, cause, p.config.CallbackResource)
	}
}

// processBufferTask imports one task, retrying transient errors inline with
// ImportErrorSleepTime sleeps until the ImportTimeout budget is exhausted.
// Terminal failure marks the buffer ImportError and fires the callback.
func (p *BulkProcessor) processBufferTask(task *BufferTask, workerID int, feedbackKeysArray []string) {

	isFailed := true
	maxLoopNum := p.config.ImportTimeout / p.config.ImportErrorSleepTime
	err := errors.New("Buffer Task timeout")

	// assign the outer err so the exhausted-budget callback below reports the
	// last real failure, not the placeholder timeout error
	for range maxLoopNum {
		if err = p.processBufferTaskWithTransaction(task, p.config.TaskTimeout); err != nil {

			Warning("Server is busy, will retry to process buffer task %s after %d seconds, error: %v",
				task.TaskId, p.config.ImportErrorSleepTime, err)

			// Update checkpoint with all error file
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
			if err2 := p.pgClient.UpdateDeltaCheckpointStatus(ctx, p.processId, []string{task.LocalFile}, CheckpointStatusFailed, -1, err.Error()); err2 != nil {
				Debug("Worker %d failed to update checkpoint for error file: %v\n", workerID, err2)
			}
			cancel()

			// all the errors without parsing error are not expected, we will retry, parsing error just call
			// the callback and continue to next batch
			shouldRetry := true
			for _, skipError := range p.config.SkipServerErrorInfos {
				if strings.Contains(err.Error(), skipError) {
					shouldRetry = false
					break
				}
			}

			if shouldRetry {
				// RetrySleepMaxTime default is 10, so the random offset is -10 to 10
				randomOffset := rand.Intn(p.config.RetrySleepMaxTime*2) - p.config.RetrySleepMaxTime
				sleepTime := p.config.ImportErrorSleepTime + randomOffset
				if sleepTime < 0 {
					sleepTime = 1
				}
				time.Sleep(time.Duration(sleepTime) * time.Second)
				continue
			}

			feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))

			if p.config.ImportErrorCallback != nil {
				Debug("Worker %d task %s failed before callback: %s",
					workerID, task.TaskId, feedbackKeysString)
				p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
			} else {
				Debug("Worker %d task %s failed with no callback: %s",
					workerID, task.TaskId, feedbackKeysString)
			}

			isFailed = true
			break
		} else {
			isFailed = false
			break
		}
	}

	if isFailed {
		p.bufferManager.SetBufferStatus(task.TaskId, BufferStatusImportError)
		feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))
		Error("Worker %d import task %s failed: %s after retry %d times", workerID, task.TaskId, feedbackKeysString, maxLoopNum)
		if p.config.ImportErrorCallback != nil {
			p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
		}
		return
	}

	if task.LocalFile == "" {
		p.bufferManager.SetBufferStatus(task.TaskId, BufferStatusImported)
		if task.MaxOffset > 0 {
			p.UpdateMaxOffset(task.MaxOffset)
		}
		return
	}

	// The shard transaction is complete. Do not hold its serial worker while
	// the control plane is unavailable, and do not delete the recovery artifact
	// until completion metadata is durable on main.
	p.bufferManager.SetBufferStatus(task.TaskId, BufferStatusCheckpointPending)
	p.metadataWg.Add(1)
	go func() {
		defer p.metadataWg.Done()
		p.completeBufferTaskMetadata(task, workerID)
	}()
}

func (p *BulkProcessor) insertDeltaCheckpointUntilDone(pgTable, localFilePath string) error {
	for {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		err := p.pgClient.InsertDeltaCheckpoint(ctx, p.processId, pgTable, localFilePath)
		cancel()
		if err == nil {
			return nil
		}
		Debug("Failed to insert delta checkpoint with new file %s; retrying: %v", localFilePath, err)
		select {
		case <-p.ctx.Done():
			return ErrProcessorClosed
		case <-time.After(time.Second):
		}
	}
}

func (p *BulkProcessor) completeBufferTaskMetadata(task *BufferTask, workerID int) {
	if task.CheckpointReady != nil {
		select {
		case err := <-task.CheckpointReady:
			if err != nil {
				Debug("Worker %d could not create checkpoint for %s; preserving recovery artifact: %v", workerID, task.LocalFile, err)
				return
			}
		case <-p.ctx.Done():
			return
		}
	}

	for {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		err := p.pgClient.UpdateDeltaCheckpointStatus(ctx, p.processId, []string{task.LocalFile}, CheckpointStatusCompleted, 0, "")
		cancel()
		if err == nil {
			if err := CleanupLocalFile(task.LocalFile); err != nil {
				Error("Worker %d failed to remove temporary file %s: %v", workerID, task.LocalFile, err)
			}
			p.bufferManager.SetBufferStatus(task.TaskId, BufferStatusImported)
			if task.MaxOffset > 0 {
				p.UpdateMaxOffset(task.MaxOffset)
			}
			return
		}
		Debug("Worker %d failed to persist completion metadata for %s; preserving artifact and retrying: %v", workerID, task.LocalFile, err)
		if p.ctx.Done() == nil {
			return
		}
		select {
		case <-p.ctx.Done():
			return
		case <-time.After(time.Second):
		}
	}
}

// processBufferTaskWithTransaction process buffer task with transaction, include delete and import
func (p *BulkProcessor) processBufferTaskWithTransaction(task *BufferTask, timeout int) error {

	deleteBeforeInsert := p.config.DeleteBeforeInsert

	if task.RecordCount <= 0 && len(task.DeletedRecords) == 0 && len(task.DeletedGroupRecords) == 0 {
		Debug("task %s has no records, skip processing", task.TaskId)
		return nil
	}

	// 300 seconds is the max timeout for the transaction
	ctx, cancel := context.WithTimeout(context.Background(), time.Duration(timeout)*time.Second)
	defer cancel()

	// sharded tasks run on the owning instance; a client-resolution failure is
	// a transient error handled by processBufferTask's retry loop
	target := p.pgClient
	if p.isSharded {
		if task.InstanceID == "" {
			return fmt.Errorf("sharded task %s has no instance id, refusing to target main", task.TaskId)
		}
		var err error
		target, err = p.instanceRouter.GetClient(ctx, task.InstanceID)
		if err != nil {
			return fmt.Errorf("failed to get client for instance %s: %w", task.InstanceID, err)
		}
	}

	conn, err := target.pool.Acquire(ctx)
	if err != nil {
		return fmt.Errorf("failed to acquire connection: %w", err)
	}
	defer conn.Release()

	isAuxFile := task.IsAux
	targetTable := p.config.PostgreSQL.Table
	if isAuxFile {
		targetTable += auxTableSuffix
	}

	updateOnConflict := p.config.UpdateOnConflict
	if deleteBeforeInsert && len(task.FileVersionMap) > 0 {
		updateOnConflict = false
	}

	tx, err := conn.Begin(ctx)
	if err != nil {
		return fmt.Errorf("failed to begin transaction: %w", err)
	}

	success := false
	defer func() {
		if !success {
			if rollbackErr := tx.Rollback(ctx); rollbackErr != nil {
				Error("task %s failed to rollback transaction: %v", task.TaskId, rollbackErr)
			}
			// detach the connection from the pool and close it manually,
			// fix the issue where a segment restart would cause the link to fail to be released
			conn := conn.Hijack()
			conn.Close(ctx)
		}
	}()

	// 1. delete records first
	for _, deletedRecord := range task.DeletedRecords {
		deleteSQL := `SELECT relyt_sys.delete_tables_with_condition(
							$1,  -- schema_name
							$2,  -- main_table
							$3,  -- file_id
							$4,  -- routing_id
							$5   -- have_aux_table
						)`

		// log.Printf("Executing delete SQL in transaction: relyt_sys.delete_tables_with_condition('%s', '%s', '%s', '%s', %t)",
		// 	p.config.PostgreSQL.Schema, p.config.PostgreSQL.Table, deletedRecord.fileID, deletedRecord.routingID, p.hasRoutingTable)

		_, err := tx.Exec(ctx, deleteSQL,
			p.config.PostgreSQL.Schema,
			p.config.PostgreSQL.Table,
			deletedRecord.fileID,
			deletedRecord.routingID,
			p.hasRoutingTable,
		)
		if err != nil {
			return fmt.Errorf("failed to execute delete SQL for %s:%s: %w", deletedRecord.fileID, deletedRecord.routingID, err)
		}
	}

	// 2. delete outdated files
	if len(task.FileVersionMap) > 0 && deleteBeforeInsert {
		if err := target.DeleteOutdatedFiles(ctx, tx, targetTable, task.FileVersionMap); err != nil {
			return fmt.Errorf("failed to delete outdated files: %w", err)
		}
	}

	// 3. import file
	if task.LocalFile != "" && task.RecordCount > 0 {
		if task.ImportStrategy == InsertOnConflict {
			if err := target.InsertIntoOnConflictFromLocal(ctx, tx, GetLocalFileFullPath(task.LocalFile), targetTable,
				GetColumnNames(p.fields), updateOnConflict, p.config.InsertIntoBatchSize); err != nil {
				return fmt.Errorf("INSERT INTO failed: %w", err)
			}
		} else if task.ImportStrategy == CopyFromLocal {
			if err := target.CopyFromLocalOnConflict(ctx, tx, GetLocalFileFullPath(task.LocalFile), targetTable, GetColumnNames(p.fields), updateOnConflict); err != nil {
				return fmt.Errorf("COPY FROM LOCAL failed: %w", err)
			}
		} else if task.ImportStrategy == CopyFromS3 {
			loadConfig := p.config
			s3Config, err := p.pgClient.GetLoadConfigFromDB(ctx, &loadConfig)
			if err != nil {
				return fmt.Errorf("failed to get S3 configuration: %w", err)
			}

			if err := target.CopyFromS3OnConflict(ctx, tx, p.s3Client.GetS3URL(task.S3File), targetTable, GetColumnNames(p.fields), updateOnConflict, *s3Config); err != nil {
				log.Printf("COPY FROM S3 failed for task %s: %v, falling back to INSERT ON CONFLICT", task.TaskId, err)
				task.ImportStrategy = InsertOnConflict
				return fmt.Errorf("COPY FROM S3 failed: %w", err)
			}
		} else if task.ImportStrategy == InsertFromExtTable {
			loadConfig := p.config
			s3Config, err := p.pgClient.GetLoadConfigFromDB(ctx, &loadConfig)
			if err != nil {
				return fmt.Errorf("failed to get S3 configuration: %w", err)
			}

			if err := target.InsertIntoFromExternalTable(ctx, tx, p.s3Client.GetS3URL(task.S3File), task.TaskId, targetTable, GetColumnNames(p.fields), updateOnConflict, *s3Config); err != nil {
				task.ImportStrategy = InsertOnConflict
				return fmt.Errorf("INSERT INTO FROM EXTERNAL TABLE failed: %w", err)
			}
		}
	}

	// 4. delete group records
	for _, deletedGroupRecord := range task.DeletedGroupRecords {
		deleteSQL := `SELECT relyt_sys.delete_tables_with_group(
							$1,  -- schema_name
							$2,  -- main_table
							$3,  -- group_id
							$4,  -- routing_id
							$5   -- have_aux_table
						)`

		_, err := tx.Exec(ctx, deleteSQL,
			p.config.PostgreSQL.Schema,
			p.config.PostgreSQL.Table,
			deletedGroupRecord.groupID,
			deletedGroupRecord.routingID,
			p.hasRoutingTable,
		)
		if err != nil {
			return fmt.Errorf("failed to execute delete SQL for %s:%s: %w", deletedGroupRecord.groupID, deletedGroupRecord.routingID, err)
		}
	}

	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("task: %s failed to commit transaction: %w", task.TaskId, err)
	}
	success = true

	return nil
}

// processSQLParams process sql params
func processSQLParams(input string, args []any) string {
	if len(args) == 0 {
		return input
	}

	// convert params to string and replace placeholder in condition
	processed := input
	for i, arg := range args {
		// format params according to type
		var valueStr string
		switch v := arg.(type) {
		case string:
			valueStr = fmt.Sprintf("'%s'", strings.ReplaceAll(v, "'", "''"))
		case nil:
			valueStr = "NULL"
		case []any:
			// process array type
			values := make([]string, len(v))
			for j, item := range v {
				switch itemVal := item.(type) {
				case string:
					values[j] = fmt.Sprintf("'%s'", strings.ReplaceAll(itemVal, "'", "''"))
				case nil:
					values[j] = "NULL"
				default:
					values[j] = fmt.Sprintf("%v", itemVal)
				}
			}
			valueStr = strings.Join(values, ",")
		case []string:
			// process string array
			values := make([]string, len(v))
			for j, item := range v {
				values[j] = fmt.Sprintf("'%s'", strings.ReplaceAll(item, "'", "''"))
			}
			valueStr = strings.Join(values, ",")
		case []int64:
			// process int64 array
			values := make([]string, len(v))
			for j, item := range v {
				values[j] = fmt.Sprintf("%d", item)
			}
			valueStr = strings.Join(values, ",")
		case []int32:
			// process int32 array
			values := make([]string, len(v))
			for j, item := range v {
				values[j] = fmt.Sprintf("%d", item)
			}
			valueStr = strings.Join(values, ",")
		case []int:
			// process int array
			values := make([]string, len(v))
			for j, item := range v {
				values[j] = fmt.Sprintf("%d", item)
			}
			valueStr = strings.Join(values, ",")
		case []float64:
			// process float64 array
			values := make([]string, len(v))
			for j, item := range v {
				values[j] = fmt.Sprintf("%f", item)
			}
			valueStr = strings.Join(values, ",")
		case []float32:
			// process float32 array
			values := make([]string, len(v))
			for j, item := range v {
				values[j] = fmt.Sprintf("%f", item)
			}
			valueStr = strings.Join(values, ",")
		case []bool:
			// process bool array
			values := make([]string, len(v))
			for j, item := range v {
				values[j] = fmt.Sprintf("%t", item)
			}
			valueStr = strings.Join(values, ",")
		default:
			valueStr = fmt.Sprintf("%v", v)
		}
		// replace placeholder
		processed = strings.Replace(processed, fmt.Sprintf("$%d", i+1), valueStr, 1)
	}
	return processed
}

// checkTableModes resolves both routing modes for a table, cached for 5
// minutes under one entry. The instance-routing existence check runs even on
// non-sharded processors so a foreign sharded table is detected and rejected
// instead of silently queried on main.
func (p *BulkProcessor) checkTableModes(tableName string) (bool, bool, error) {
	tableName = strings.ToLower(tableName)

	p.routingTableCacheMutex.RLock()
	ret, exists := p.routingTableCache[tableName]
	p.routingTableCacheMutex.RUnlock()
	if exists && time.Since(ret.lastCheckTime) <= 5*time.Minute {
		return ret.hasRoutingTable, ret.isSharded, nil
	}

	routingTableName := fmt.Sprintf("%s%s", tableName, routingTableSuffix)
	Log("CheckTableHasRoutingTable: %s, routingTableName: %s", tableName, routingTableName)
	hasRoutingTable, err := p.pgClient.HasRoutingTable(p.ctx, routingTableName)
	if err != nil {
		return false, false, errors.Wrap(err, "failed to check if routing table exists")
	}

	instanceRoutingTableName := fmt.Sprintf("%s%s", tableName, instanceRoutingTableSuffix)
	isSharded, err := p.pgClient.HasRoutingTable(p.ctx, instanceRoutingTableName)
	if err != nil {
		return false, false, errors.Wrap(err, "failed to check if instance routing table exists")
	}

	p.routingTableCacheMutex.Lock()
	p.routingTableCache[tableName] = routingTableCacheEntry{
		lastCheckTime:   time.Now(),
		hasRoutingTable: hasRoutingTable,
		isSharded:       isSharded,
	}
	p.routingTableCacheMutex.Unlock()

	return hasRoutingTable, isSharded, nil
}

func (p *BulkProcessor) CheckTableHasRoutingTable(tableName string) (bool, error) {
	hasRoutingTable, _, err := p.checkTableModes(tableName)
	return hasRoutingTable, err
}

// CheckTableIsSharded reports whether <table>_relyt_instance_routing exists.
func (p *BulkProcessor) CheckTableIsSharded(tableName string) (bool, error) {
	_, isSharded, err := p.checkTableModes(tableName)
	return isSharded, err
}

// SearchJsonRowsV2 return pgx.Rows object, let caller control the iteration
// caller need to call rows.Next() and rows.Scan()
func (p *BulkProcessor) SearchJsonRowsV2(options *SearchOptions, args ...any) (pgx.Rows, error) {
	p.mutex.RLock()
	if p.isShutdown {
		p.mutex.RUnlock()
		return nil, ErrProcessorClosed
	}
	p.mutex.RUnlock()

	if options.Table == "" {
		return nil, ErrPostgreSQLTableRequired
	} else {
		options.Table = strings.ToLower(options.Table)
	}

	// process column names
	processedColumns := make([]string, len(options.Columns))
	for i, col := range options.Columns {
		processedColumns[i] = processSQLParams(col, args)
	}

	// process condition params
	processedCondition := processSQLParams(options.Condition, args)

	// process GroupBy params
	processedGroupBy := processSQLParams(options.GroupBy, args)
	processedHaving := processSQLParams(options.Having, args)

	if handled, rows, err := p.routeSearchJsonRows(p.ctx, options, processedColumns, processedCondition, processedGroupBy, processedHaving); handled {
		return rows, err
	}

	hasRoutingTable, err := p.CheckTableHasRoutingTable(options.Table)
	if err != nil {
		return nil, errors.Wrap(err, "failed to check if routing table exists")
	}

	// prepare params
	params := []any{
		p.config.PostgreSQL.Schema,
		options.Table,
		pq.Array(processedColumns),
		processedCondition,
		options.OrderBy,
		processedGroupBy,
		processedHaving,
		options.Limit,
		options.Offset,
		hasRoutingTable,
	}

	// log.Printf("baseSQL: select * from get_columns_with_condition('%v', '%v', '%v', '%v', '%v', '%v', '%v', '%v', '%v', %t)", params...)

	rows, finalSQL, err := p.pgClient.GetColumnsWithCondition(p.ctx, params...)
	options.FinalSQL = finalSQL
	if err != nil {
		return nil, errors.Wrap(err, "failed to get columns with condition")
	}

	return rows, nil
}

// SearchV2 search data from main table and aux table
func (p *BulkProcessor) SearchV2(options *SearchOptions, args ...any) (*SearchResult, error) {
	// 复用SearchJsonRowsV2的逻辑获取rows
	rows, err := p.SearchJsonRowsV2(options, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	// use input column names as result column names
	var allRows [][]any
	var jsonCols []string

	for rows.Next() {
		var resultJSON []byte
		if err := rows.Scan(&resultJSON); err != nil {
			return nil, errors.Wrap(err, "rows.Scan")
		}

		// parse JSONB result
		var rowData map[string]any
		if err := json.Unmarshal(resultJSON, &rowData); err != nil {
			return nil, errors.Wrap(err, "json.Unmarshal")
		}

		// use JSON result column order to build result row
		row := make([]any, len(rowData))
		if jsonCols == nil {
			// extract key order from original JSON string
			decoder := json.NewDecoder(strings.NewReader(string(resultJSON)))
			decoder.UseNumber() // use Number type to keep precision

			// read start object token
			if _, err := decoder.Token(); err != nil {
				return nil, errors.Wrap(err, "read start token")
			}

			// read all keys
			jsonCols = make([]string, 0, len(rowData))
			for decoder.More() {
				token, err := decoder.Token()
				if err != nil {
					return nil, errors.Wrap(err, "read key token")
				}
				key, ok := token.(string)
				if !ok {
					return nil, errors.New("invalid key type")
				}
				jsonCols = append(jsonCols, key)

				// skip value
				if _, err := decoder.Token(); err != nil {
					return nil, errors.Wrap(err, "skip value")
				}
			}
		}

		for i, col := range jsonCols {
			row[i] = rowData[col]
		}

		allRows = append(allRows, row)
	}

	if err := rows.Err(); err != nil {
		return nil, errors.Wrap(err, "rows iteration")
	}

	// if no data, return empty result
	if len(allRows) == 0 {
		return &SearchResult{Columns: []string{}, Rows: [][]any{}}, nil
	}

	return &SearchResult{Columns: jsonCols, Rows: allRows}, nil
}

func (p *BulkProcessor) SearchJsonV2(options *SearchOptions, args ...any) ([]json.RawMessage, error) {
	rows, err := p.SearchJsonRowsV2(options, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var jsonResults []json.RawMessage

	for rows.Next() {
		var resultJSON []byte
		if err := rows.Scan(&resultJSON); err != nil {
			return nil, errors.Wrap(err, "rows.Scan")
		}

		jsonResults = append(jsonResults, resultJSON)
	}

	if err := rows.Err(); err != nil {
		return nil, errors.Wrap(err, "rows iteration")
	}

	return jsonResults, nil
}

// SearchJsonRowsWithContextV2 return pgx.Rows object with context to control the query time,
// let caller control the iteration caller need to call rows.Next() and rows.Scan()
// The caller is responsible for managing the context lifecycle
func (p *BulkProcessor) SearchJsonRowsWithContextV2(ctx context.Context, options *SearchOptions, args ...any) (pgx.Rows, error) {
	p.mutex.RLock()
	if p.isShutdown {
		p.mutex.RUnlock()
		return nil, ErrProcessorClosed
	}
	p.mutex.RUnlock()

	if options.Table == "" {
		return nil, ErrPostgreSQLTableRequired
	} else {
		options.Table = strings.ToLower(options.Table)
	}

	// process column names
	processedColumns := make([]string, len(options.Columns))
	for i, col := range options.Columns {
		processedColumns[i] = processSQLParams(col, args)
	}

	// process condition params
	processedCondition := processSQLParams(options.Condition, args)

	// process GroupBy params
	processedGroupBy := processSQLParams(options.GroupBy, args)
	processedHaving := processSQLParams(options.Having, args)

	if handled, rows, err := p.routeSearchJsonRows(ctx, options, processedColumns, processedCondition, processedGroupBy, processedHaving); handled {
		return rows, err
	}

	hasRoutingTable, err := p.CheckTableHasRoutingTable(options.Table)
	if err != nil {
		return nil, errors.Wrap(err, "failed to check if routing table exists")
	}

	// prepare params
	params := []any{
		p.config.PostgreSQL.Schema,
		options.Table,
		pq.Array(processedColumns),
		processedCondition,
		options.OrderBy,
		processedGroupBy,
		processedHaving,
		options.Limit,
		options.Offset,
		hasRoutingTable,
	}

	// log.Printf("baseSQL: select * from get_columns_with_condition('%v', '%v', '%v', '%v', '%v', '%v', '%v', '%v', '%v', %t)", params...)
	start := time.Now()

	rows, finalSQL, err := p.pgClient.GetColumnsWithCondition(ctx, params...)
	options.FinalSQL = finalSQL

	if err != nil {
		if ctx.Err() == context.DeadlineExceeded {
			return nil, errors.New(fmt.Sprintf("search timeout with time cost: %v", time.Since(start)))
		}

		return nil, errors.Wrap(err, "failed to get columns with condition")
	}

	return rows, nil
}

// UpdateByQueryOptions 定义update_by_query的选项
type UpdateByQueryOptions struct {
	Table     string
	Condition string
	Updates   map[string]any
	FinalSQL  string
	RoutingID string // required on instance-sharded tables (routes to the owning instance); ignored otherwise
}

func (p *BulkProcessor) UpdateByQueryWithContextV2(ctx context.Context, options *UpdateByQueryOptions, args ...any) (int64, error) {
	p.mutex.RLock()
	if p.isShutdown {
		p.mutex.RUnlock()
		return 0, ErrProcessorClosed
	}
	p.mutex.RUnlock()

	if options.Table == "" {
		return 0, ErrPostgreSQLTableRequired
	}

	options.Table = strings.ToLower(options.Table)

	processedCondition := processSQLParams(options.Condition, args)

	// 构建更新字段的SQL
	if len(options.Updates) == 0 {
		return 0, errors.New("no update fields specified")
	}

	// 使用 processSQLParams 处理 Updates 中的字符串表达式占位符
	processedUpdates := make(map[string]any, len(options.Updates))
	for field, value := range options.Updates {
		if expr, ok := value.(string); ok {
			processedUpdates[field] = processSQLParams(expr, args)
			continue
		}
		processedUpdates[field] = value
	}

	// own table: sharded mode is fixed at startup, so warm processes never
	// round-trip to main here; foreign sharded tables fail closed
	if strings.EqualFold(options.Table, p.config.PostgreSQL.Table) {
		if p.isSharded {
			return p.updateByQuerySharded(ctx, options, processedCondition, processedUpdates)
		}
	} else {
		isSharded, err := p.CheckTableIsSharded(options.Table)
		if err != nil {
			return 0, errors.Wrap(err, "failed to check if table is sharded")
		}
		if isSharded {
			return 0, errors.Wrapf(ErrForeignShardedTable,
				"update on sharded table %s (processor configured for table %q)",
				options.Table, p.config.PostgreSQL.Table)
		}
	}

	hasRoutingTable, err := p.CheckTableHasRoutingTable(options.Table)
	if err != nil {
		return 0, errors.Wrap(err, "failed to check if routing table exists")
	}

	start := time.Now()

	updatedCount, finalSQL, err := p.pgClient.UpdateByQueryV2(ctx,
		p.config.PostgreSQL.Schema,
		options.Table,
		processedCondition,
		processedUpdates,
		hasRoutingTable)

	options.FinalSQL = finalSQL

	if err != nil {
		if ctx.Err() == context.DeadlineExceeded {
			return 0, errors.New(fmt.Sprintf("update timeout with time cost: %v", time.Since(start)))
		}

		return 0, errors.Wrap(err, "failed to update by query")
	}

	return updatedCount, nil
}
