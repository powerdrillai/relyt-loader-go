// GetMaxOffset returns the global maximum offset
func (p *BulkProcessor) GetMaxOffset() int64 {
	return p.maxOffset.Load()
}

// UpdateMaxOffset updates the global maximum offset if the new offset is greater
func (p *BulkProcessor) UpdateMaxOffset(newOffset int64) {
	for {
		current := p.maxOffset.Load()
		if newOffset <= current {
			break
		}
		if p.maxOffset.CompareAndSwap(current, newOffset) {
			break
		}
	}
}

// Start starts the importer thread.
func (p *BulkProcessor) Start() error {
	return p.start(false)
}

// ensureStarted is the idempotent admission path used by concurrent API calls.
func (p *BulkProcessor) ensureStarted() error {
	return p.start(true)
}

func (p *BulkProcessor) start(idempotent bool) error {
	p.mutex.Lock()
	defer p.mutex.Unlock()

	if p.isShutdown {
		return ErrProcessorClosed
	}
	if p.isStarted {
		if idempotent {
			return nil
		}
		return errors.New("bulk processor already started")
	}

	p.isStarted = true

	if p.config.PostgreSQL.Table == "" {
		Log("BulkProcessor Start: PostgreSQL table is empty, skip start background threads")
		return nil
	}

	if p.hasRoutingTable {
		p.importerWg.Add(1)
		go p.ListenThread()
	}

	if p.isSharded {
		p.importerWg.Add(1)
		go p.RegistryListenThread()
	}

	p.importerWg.Add(1)
	go p.InsertThread()

	p.importerWg.Add(1)
	go p.ImporterThread()

	p.importerWg.Add(1)
	go p.AutoFlushThread()

	p.importerWg.Add(1)
	go p.BGWorkerThread()

	if p.config.EnableDualBuffer {

		p.bufferThreadWg.Add(1)
		go p.InsertThreadV2()

		p.bufferThreadWg.Add(1)
		go p.ImporterThreadV2()
	}

	return nil
}

// Shutdown shuts down the processor
func (p *BulkProcessor) Shutdown() error {
	// only check-and-set under the lock: the shutdown drain fires error
	// callbacks that may re-enter processor APIs taking p.mutex
	p.mutex.Lock()
	if p.isShutdown {
		p.mutex.Unlock()
		return nil
	}
	p.isShutdown = true
	p.mutex.Unlock()

	p.cancel()

	// Wait out any active API admission or Flush and prevent either from racing
	// teardown. Calls arriving afterward observe isShutdown.
	p.admissionGate.Lock()
	p.admissionGate.Unlock()
	p.flushMutex.Lock()
	p.flushMutex.Unlock()

	// Every admitted producer either publishes its work or observes cancellation
	// and rolls back before consumers and clients are torn down.
	p.admissionWg.Wait()

	// Wait for importer to finish
	p.importerWg.Wait()

	// Wait for buffer threads to finish (if dual buffer is enabled)
	if p.config.EnableDualBuffer {
		p.bufferThreadWg.Wait()
		// wait for all import workers to finish
		p.workerWg.Wait()
	}
	p.metadataWg.Wait()

	// Create a list of all files that need to be cleaned up from S3
	allFiles := append(
		p.fileManager.GetFilesByState(FileStateFrozen),
		append(
			p.fileManager.GetFilesByState(FileStateImporting),
			p.fileManager.GetFilesByState(FileStateImported)...,
		)...,
	)

	// Cleanup files from local filesystem
	for _, file := range allFiles {
		if err := file.CleanupFile(); err != nil {
			fmt.Fprintf(os.Stderr, "Failed to cleanup local file: %v\n", err)
		}
	}

	// Cleanup S3 files
	// First gather all S3 keys that need to be deleted
	var s3Keys []string
	var normalFilepaths []string
	for _, file := range allFiles {
		if file.S3Key != "" && file.State != FileStateError && false {
			s3Keys = append(s3Keys, file.S3Key)
			normalFilepaths = append(normalFilepaths, file.S3Key)
		}
	}

	// Delete files from S3 if there are any
	if len(s3Keys) > 0 {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		if err := p.s3Client.DeleteObjects(ctx, s3Keys); err != nil {
			fmt.Fprintf(os.Stderr, "Failed to delete S3 objects during shutdown: %v\n", err)
		}
		cancel()
	}

	// Cleanup buffer files
	normalFilepaths = append(normalFilepaths, p.bufferManager.RecycleBuffers()...)

	// Cleanup checkpoint records
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	if err := p.pgClient.DeleteDeltaCheckpointByProcessIdAndFilepaths(ctx, p.processId, normalFilepaths); err != nil {
		fmt.Fprintf(os.Stderr, "Failed to delete checkpoint records during shutdown: %v\n", err)
	}
	cancel()

	// Close clients
	if p.instanceRouter != nil {
		p.instanceRouter.Close()
	}
	p.pgClient.Close()

	return nil
}

func (p *BulkProcessor) beginAdmission() (context.Context, error) {
	p.admissionGate.RLock()
	p.mutex.RLock()
	defer p.mutex.RUnlock()
	if p.isShutdown {
		p.admissionGate.RUnlock()
		return nil, ErrProcessorClosed
	}
	p.admissionWg.Add(1)
	return p.ctx, nil
}

func (p *BulkProcessor) endAdmission() {
	p.admissionWg.Done()
	p.admissionGate.RUnlock()
}

func (p *BulkProcessor) enqueueValues(ctx context.Context, values []string) error {
	p.recordsNum.Add(1)
	select {
	case p.recordsQueue <- values:
		return nil
	case <-ctx.Done():
		p.recordsNum.Add(-1)
		return ErrProcessorClosed
	}
}

func (p *BulkProcessor) enqueueRecordV2(ctx context.Context, record *Record) error {
	p.recordsNum.Add(1)
	select {
	case p.recordQueueV2 <- record:
		return nil
	case <-ctx.Done():
		p.recordsNum.Add(-1)
		return ErrProcessorClosed
	}
}

func (p *BulkProcessor) ensureRecordSchema(val reflect.Value) error {
	elemType := val.Type().Elem()
	if elemType.Kind() == reflect.Pointer {
		elemType = elemType.Elem()
	}
	if elemType.Kind() != reflect.Struct {
		return errors.New("input must be a slice of structs")
	}

	p.schemaMutex.Lock()
	defer p.schemaMutex.Unlock()
	if p.structType != nil {
		if p.structType != elemType {
			return errors.Wrapf(ErrRecordTypeMismatch, "processor uses %s, supplied %s", p.structType, elemType)
		}
		return nil
	}

	fields, err := GetStructFields(elemType)
	if err != nil {
		return err
	}
	if len(fields) == 0 {
		return errors.New("no valid fields found in struct")
	}

	routingColIndex := getValueColumnIndex(fields, "routing_id")
	if p.isSharded && routingColIndex < 0 {
		return ErrRoutingColumnRequired
	}
	pkColumnsIndex := make([]int, len(p.pkColumns))
	for i, columnName := range p.pkColumns {
		pkColumnsIndex[i] = getValueColumnIndex(fields, columnName)
		if pkColumnsIndex[i] < 0 {
			return errors.Wrapf(ErrPrimaryKeyColumnRequired, "primary-key column %q", columnName)
		}
	}

	// Publish the complete immutable snapshot only after every validation passes.
	p.structType = elemType
	p.fields = fields
	p.routingColIndex = routingColIndex
	p.versionColIndex = getValueColumnIndex(fields, "version")
	p.pkColumnsIndex = pkColumnsIndex
	p.feedFieldIndex = getValueColumnIndex(fields, p.config.FeedbackColumn)
	return nil
}

// checkErrorCount checks if the current error can be ignored based on max error limit
// returns true if the error should be ignored, false if the error should be returned
func (p *BulkProcessor) checkErrorCount(err error, errorRecordsCount *int, recordIndex int, errorContext string) bool {
	if p.config.MaxErrorRecords <= 0 {
		return false
	}

	// Check if we've reached the max error limit
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	currentErrorCount, getErr := p.pgClient.GetCheckpointErrorRecords(ctx, p.processId)
	cancel()

	if getErr != nil {
		fmt.Fprintf(os.Stderr, "Failed to get current error count: %v\n", getErr)
		return false
	}

	if currentErrorCount+*errorRecordsCount+1 <= p.config.MaxErrorRecords {
		// This error is within our acceptable limit
		*errorRecordsCount++
		fmt.Fprintf(os.Stderr, "Ignoring error %s record %d: %v (total errors: %d/%d)\n",
			errorContext, recordIndex, err, currentErrorCount+*errorRecordsCount, p.config.MaxErrorRecords)
		return true
	}

	return false
}

// Insert inserts data into the processor
func (p *BulkProcessor) Insert(data any) error {

	if p.config.PostgreSQL.Table == "" {
		return ErrPostgreSQLTableRequired
	}

	if p.isSharded {
		return ErrShardedRequiresV2
	}

	p.mutex.RLock()
	if p.isShutdown {
		p.mutex.RUnlock()
		return ErrProcessorClosed
	}
	p.mutex.RUnlock()

	// Concurrent API calls use an idempotent lifecycle check under one lock.
	if err := p.ensureStarted(); err != nil {
		return err
	}
	admissionCtx, err := p.beginAdmission()
	if err != nil {
		return err
	}
	defer p.endAdmission()

	// Check if data is a slice
	val := reflect.ValueOf(data)
	if val.Kind() == reflect.Pointer {
		val = val.Elem()
	}

	if val.Kind() != reflect.Slice {
		return ErrInvalidInput
	}

	if val.Len() == 0 {
		return ErrEmptyInput
	}

	if err := p.ensureRecordSchema(val); err != nil {
		return err
	}

	// To track error records in this batch
	errorRecordsCount := 0

	// Process each record
	for i := 0; i < val.Len(); i++ {
		elemVal := val.Index(i)
		if elemVal.Kind() == reflect.Pointer {
			if elemVal.IsNil() {
				continue
			}
			elemVal = elemVal.Elem()
		}

		// Get field values
		values, err := GetFieldValues(elemVal.Interface(), p.fields)
		if err != nil {
			if p.checkErrorCount(err, &errorRecordsCount, i, "in") {
				continue // Skip this record and continue
			}

			// Either too many errors or couldn't get error count
			return err
		}

		if err := p.enqueueValues(admissionCtx, values); err != nil {
			return err
		}
	}

	return nil
}

// consume records from the recordsQueue and process them
func (p *BulkProcessor) InsertThread() error {
	defer p.importerWg.Done()

	var localRoutingInited = false
	var localRoutingHashSet map[string]struct{}

	for {
		select {
		case <-p.ctx.Done():
			log.Println("Insert thread context canceled, exiting...")
			return nil
		case <-p.routingQueue:
			p.routingMutex.Lock()
			localRoutingHashSet = p.routingHashSet
			localRoutingInited = true
			p.routingMutex.Unlock()
		case values := <-p.recordsQueue:
			if p.feedFieldIndex >= 0 {
				index := p.feedFieldIndex
				p.feedbackKeysMutex.Lock()
				// Check if feedback column value already exists in the map
				if _, exists := p.feedbackKeys[values[index]]; !exists {
					// Add the feedback column value to the map
					p.feedbackKeys[values[index]] = true
				} else {
					// If it already exists, we can skip adding it again
					log.Printf("Feedback key already exists: %s", values[index])
				}
				p.feedbackKeysMutex.Unlock()
			}

			toAuxFile := false
			if p.routingColIndex >= 0 {
				if !localRoutingInited {
					p.routingMutex.Lock()
					localRoutingHashSet = p.routingHashSet
					localRoutingInited = true
					p.routingMutex.Unlock()
					log.Printf("Init localRoutingHashSet, size is: %d", len(localRoutingHashSet))
				}
				if _, exists := localRoutingHashSet[values[p.routingColIndex]]; exists {
					toAuxFile = true
				}
			}

			p.fileManager.fileOperationsMutex.Lock()

			currentFile := p.fileManager.GetCurrentFile(toAuxFile)
			if currentFile == nil || currentFile.State != FileStateOpen {
				log.Printf("InsertThread Current file is nil or not open, creating a new file, toAuxFile: %v", toAuxFile)
				// Create a new file
				columnNames := GetColumnNames(p.fields)
				var err error
				currentFile, err = p.fileManager.CreateFile(columnNames, toAuxFile)
				if err != nil {
					feedbackKeysArray := p.getFeedbackValues()
					if p.config.ImportErrorCallback != nil {
						p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
					} else {
						feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))
						log.Printf("Batch import failed with no callback: %s", feedbackKeysString)
					}
					p.fileManager.fileOperationsMutex.Unlock()
					p.recordsNum.Add(-1)
					continue
				}
				p.fileManager.SetCurrentFile(currentFile, toAuxFile)
				log.Printf("InsertThread Current file created: %s", currentFile.S3Key)

				// Update checkpoint with new file
				ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
				defer cancel()

				targetTable := p.config.PostgreSQL.Table
				if toAuxFile {
					targetTable = p.GetAuxTableName()
				}
				pgTable := fmt.Sprintf("%s.%s", p.config.PostgreSQL.Schema, targetTable)

				if err := p.pgClient.InsertDeltaCheckpoint(ctx, p.processId, pgTable, currentFile.S3Key); err != nil {
					Debug("Failed to insert delta checkpoint with new file: %s, %v", currentFile.S3Key, err)
				}
			}
			//log.Printf("InsertThread Current file state: %v, num records: %d", currentFile.State, currentFile.NumRecords)
			// Write record to file
			err := currentFile.WriteRecord(values)
			if err != nil {
				feedbackKeysArray := p.getFeedbackValues()
				if p.config.ImportErrorCallback != nil {
					p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
				} else {
					feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))
					log.Printf("Batch import failed with no callback: %s", feedbackKeysString)
				}
				p.fileManager.fileOperationsMutex.Unlock()
				p.recordsNum.Add(-1)
				continue
			}

			// Check if file is full
			if currentFile.IsFull(p.config.BatchSize) {
				// Flush and close the file
				if err := currentFile.Flush(); err != nil {
					feedbackKeysArray := p.getFeedbackValues()
					if p.config.ImportErrorCallback != nil {
						p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
					} else {
						feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))
						log.Printf("Batch import failed with no callback: %s", feedbackKeysString)
					}
					p.fileManager.fileOperationsMutex.Unlock()
					p.recordsNum.Add(-1)
					continue
				}

				// Close the file to finalize the S3 upload
				if err := currentFile.Close(); err != nil {
					feedbackKeysArray := p.getFeedbackValues()
					if p.config.ImportErrorCallback != nil {
						p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
					} else {
						feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))
						log.Printf("Batch import failed with no callback: %s", feedbackKeysString)
					}
					p.fileManager.fileOperationsMutex.Unlock()
					p.recordsNum.Add(-1)
					continue
				}

				p.fileManager.fileOperationsMutex.Unlock()

				// Set S3 URL
				currentFile.S3URL = p.s3Client.GetS3URL(currentFile.S3Key)

				// Update file state to frozen
				p.fileManager.UpdateFileState(currentFile.ID, FileStateFrozen)

				if err := p.AddFileToPendingBatchFiles(currentFile); err != nil {
					feedbackKeysArray := p.getFeedbackValues()
					if p.config.ImportErrorCallback != nil {
						p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
					} else {
						feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))
						log.Printf("Batch import failed with no callback: %s", feedbackKeysString)
					}
					p.recordsNum.Add(-1)
					continue
				}
			} else {
				p.fileManager.fileOperationsMutex.Unlock()
			}
			p.recordsNum.Add(-1)
		}
	}
}

func (p *BulkProcessor) getLastFlushTime() time.Time {
	p.lastFlushMutex.RLock()
	defer p.lastFlushMutex.RUnlock()
	return p.lastFlushTime
}

func (p *BulkProcessor) setLastFlushTime(now time.Time) {
	p.lastFlushMutex.Lock()
	p.lastFlushTime = now
	p.lastFlushMutex.Unlock()
}

// Flush flushes all pending data and waits for import to complete
func (p *BulkProcessor) Flush() error {
	p.flushMutex.Lock()
	defer p.flushMutex.Unlock()

	p.admissionGate.Lock()
	gateHeld := true
	defer func() {
		if gateHeld {
			p.admissionGate.Unlock()
		}
	}()

	p.mutex.Lock()
	if p.isShutdown {
		p.mutex.Unlock()
		return ErrProcessorClosed
	}
	p.mutex.Unlock()

	// Wait for admitted records to reach their buffer, but remain responsive to
	// shutdown/cancellation.
	for p.recordsNum.Load() != 0 {
		Debug("Flush wait for recordsNum to be 0, current recordsNum: %d", p.recordsNum.Load())
		select {
		case <-p.ctx.Done():
			return ErrProcessorClosed
		case <-time.After(10 * time.Millisecond):
		}
	}

	needFlushBufferIds := []string{}
	var bufferSaveErr error

	// flush buffer
	if p.config.EnableDualBuffer {
		for _, key := range p.bufferManager.GetCurrentBufferKeys() {
			p.bufferManager.bufferOperationsMutex.Lock()
			currentBuffer := p.bufferManager.GetCurrentBuffer(key)
			if currentBuffer != nil && currentBuffer.GetRecordCount() > 0 && p.bufferManager.IsActive(currentBuffer.ID) {
				// deactivate current buffer, create new buffer
				p.bufferManager.SetBufferStatus(currentBuffer.ID, BufferStatusFrozen)
				p.bufferManager.SetCurrentBuffer(nil, key)
				p.bufferManager.bufferOperationsMutex.Unlock()

				if err := p.SaveBufferToFileAndGenerateTask(currentBuffer, currentBuffer.IsAux); err != nil {
					p.bufferManager.SetBufferStatus(currentBuffer.ID, BufferStatusFlushError)
					feedbackKeysArray := currentBuffer.GetFeedbackKeys()
					feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))

					if p.config.ImportErrorCallback != nil {
						Warning("save file: %s failed before callback: %s", currentBuffer.ID, feedbackKeysString)
						p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
					} else {
						Warning("save file: %s failed with no callback: %s", currentBuffer.ID, feedbackKeysString)
					}
					if bufferSaveErr == nil {
						bufferSaveErr = err
					}
					continue
				}
			} else {
				p.bufferManager.bufferOperationsMutex.Unlock()
			}
		}

		buffers := p.bufferManager.GetBufferByStatus(BufferStatusFlushed, BufferStatusFrozen)
		for _, buffer := range buffers {
			needFlushBufferIds = append(needFlushBufferIds, buffer.ID)
		}
	}
	if bufferSaveErr != nil {
		return errors.Wrap(bufferSaveErr, "failed to save buffer during flush")
	}

	p.fileManager.fileOperationsMutex.Lock()
	for _, isAux := range []bool{false, true} {
		// Flush current file if it has records
		currentFile := p.fileManager.GetCurrentFile(isAux)
		if currentFile != nil && currentFile.State == FileStateOpen && currentFile.NumRecords > 0 {
			Debug("Flushing current file: %s", currentFile.S3Key)
			if err := currentFile.Flush(); err != nil {
				p.fileManager.fileOperationsMutex.Unlock()
				return err
			}

			// Close the file to finalize the S3 upload
			if err := currentFile.Close(); err != nil {
				p.fileManager.fileOperationsMutex.Unlock()
				return err
			}

			// Set S3 URL
			currentFile.S3URL = p.s3Client.GetS3URL(currentFile.S3Key)

			// Update file state to frozen
			p.fileManager.UpdateFileState(currentFile.ID, FileStateFrozen)

			if err := p.AddFileToPendingBatchFiles(currentFile); err != nil {
				p.fileManager.fileOperationsMutex.Unlock()
				return err
			}

			// next CreateFile will reset the batchCounter
			currentFileInfo := p.fileManager.GetCurrentFileInfo(isAux)
			currentFileInfo.batchCounter = p.config.BatchImportSize
		}
	}

	batchDir := ""
	sendDirectory := false

	// flush all pendingBatchFiles
	p.pendingBatchMutex.Lock()
	for dir, count := range p.pendingBatchFiles {
		if count > 0 {
			sendDirectory = true
			Debug("Queuing batch directory for import: %s with %d files", dir, count)
			batchDir = dir
			select {
			case p.batchQueue <- dir:
			case <-p.ctx.Done():
				p.pendingBatchMutex.Unlock()
				p.fileManager.fileOperationsMutex.Unlock()
				return ErrProcessorClosed
			}
		}
		delete(p.pendingBatchFiles, dir)
	}
	p.setLastFlushTime(time.Now())
	p.pendingBatchMutex.Unlock()

	p.fileManager.fileOperationsMutex.Unlock()

	// The barrier has captured and frozen all work admitted before Flush. Do not
	// block later cached-tenant admissions while imports/checkpoint metadata are
	// completing.
	p.admissionGate.Unlock()
	gateHeld = false

	// if no directory send to import, return ASAP
	if !sendDirectory && len(needFlushBufferIds) == 0 {
		Debug("flush without any data")
		return nil
	}

	// Wait for all files to be imported or an error to occur
	for {
		// Check for context cancellation
		select {
		case <-p.ctx.Done():
			// Context canceled, might be a shutdown
			// Only report it as an error if we're not in shutdown
			p.mutex.RLock()
			isShutdown := p.isShutdown
			p.mutex.RUnlock()

			if !isShutdown {
				return errors.New("import process canceled")
			}
			// shutdown abandons queued buffers in Flushed status (artifacts
			// preserved for recovery); waiting on them would never terminate
			return ErrProcessorClosed
		default:
			// Not canceled
		}

		// Check if all files are imported under the given directory
		frozenFiles := p.fileManager.GetFilesByStateAndDirectory(FileStateFrozen, batchDir)
		importingFiles := p.fileManager.GetFilesByStateAndDirectory(FileStateImporting, batchDir)
		errorFiles := p.fileManager.GetFilesByStateAndDirectory(FileStateError, batchDir)

		flushingBuffers := []*Buffer{}
		errorBuffers := []*Buffer{}

		for _, bufferId := range needFlushBufferIds {
			buffer := p.bufferManager.GetBufferByID(bufferId)
			status, exists := p.bufferManager.GetBufferStatus(bufferId)
			if buffer != nil && exists {
				switch status {
				case BufferStatusFlushError, BufferStatusImportError:
					errorBuffers = append(errorBuffers, buffer)
				case BufferStatusFrozen, BufferStatusFlushed, BufferStatusCheckpointPending:
					flushingBuffers = append(flushingBuffers, buffer)
				}
			}
		}

		if len(errorFiles)+len(errorBuffers) > 0 {
			// sleep at least 100ms because there are two updates to checkpoint
			sleepTime := max(p.config.FlushSleepTime, 1000)
			time.Sleep(time.Duration(sleepTime) * time.Millisecond)

			return errors.New("import failed, check delta checkpoint for more details")
		}

		// If no files are pending, we're done
		if len(frozenFiles) == 0 && len(importingFiles) == 0 && len(flushingBuffers) == 0 {
			Debug("No files to import, exiting...")
			return nil
		}

		// Short sleep to avoid excessive CPU usage
		time.Sleep(time.Duration(p.config.FlushSleepTime) * time.Millisecond)
	}
}

// importerThread processes files from the queue
func (p *BulkProcessor) ImporterThread() {
	defer p.importerWg.Done()

	for {
		select {
		case <-p.ctx.Done():
			log.Println("Importer thread context canceled, exiting...")
			return

		case batchDir := <-p.batchQueue:
			log.Printf("Geting batch directory for import: %s", batchDir)
			// Process a whole batch directory
			if batchDir == "" {
				continue
			}

			// Get all files in this batch directory
			files := p.fileManager.GetFilesByBatchDirectory(batchDir)
			if len(files) == 0 {
				continue
			}

			feedbackKeysArray := p.getFeedbackValues()

			// Update state of all files to importing
			for _, file := range files {
				// Skip if not in frozen state
				if file.State != FileStateFrozen {
					continue
				}
				// Update state to importing
				p.fileManager.UpdateFileState(file.ID, FileStateImporting)
			}

			isAuxFile := strings.Contains(batchDir, BatchPrefixAux)
			// Import the entire batch directory
			isFailed := true
			maxLoopNum := p.config.ImportTimeout / p.config.ImportErrorSleepTime
			err := errors.New("import batch directory timeout")
			for range maxLoopNum {
				err = p.importBatchDirectory(batchDir, isAuxFile)
				if err != nil {
					var filepaths []string
					for _, file := range files {
						filepaths = append(filepaths, file.S3Key)
					}

					// Update checkpoint with all error file
					ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
					if err2 := p.pgClient.UpdateDeltaCheckpointStatus(ctx, p.processId, filepaths, CheckpointStatusFailed, -1, err.Error()); err2 != nil {
						fmt.Fprintf(os.Stderr, "Failed to update checkpoint for error file: %v\n", err2)
					}
					cancel()

					// all the errors without parsing error are not expected, we will retry, parsing error just call
					// the callback and continue to next batch
					if !strings.Contains(err.Error(), "Bad literal") && !strings.Contains(err.Error(), "Dimensions") {
						time.Sleep(time.Duration(p.config.ImportErrorSleepTime) * time.Second)
						continue
					}

					// Mark all files as error
					for _, file := range files {
						file.SetError(fmt.Sprintf("failed to load batch: %v", err))
					}

					feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))

					if p.config.ImportErrorCallback != nil {
						log.Printf("Batch import failed before callback: %s", feedbackKeysString)
						p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
					} else {
						log.Printf("Batch import failed with no callback: %s", feedbackKeysString)
					}

					// continue to next batch, it is more reasonable to continue processing if upper-level
					// does not exit in the callback.
					isFailed = true
					break
				} else {
					isFailed = false
					break
				}
			}

			if isFailed {
				feedbackKeysString := fmt.Sprintf("failed %s is [%s].", p.config.FeedbackColumn, strings.Join(feedbackKeysArray, ","))
				log.Printf("Import batch directory timeout: %s", feedbackKeysString)
				if p.config.ImportErrorCallback != nil {
					p.config.ImportErrorCallback(p.config.FeedbackColumn, feedbackKeysArray, err, p.config.CallbackResource)
				}
				continue
			}

			// Update all files to imported state
			var filepaths []string
			for _, file := range files {
				// Update state to imported and record import time
				file.ImportedAt = time.Now()
				log.Printf("File imported: %s", file.S3Key)

				p.fileManager.UpdateFileState(file.ID, FileStateImported)

				// Cleanup file
				if err := file.CleanupFile(); err != nil {
					fmt.Fprintf(os.Stderr, "Failed to cleanup file: %v\n", err)
				}
				filepaths = append(filepaths, file.S3Key)
			}

			// Update checkpoint with all imported file
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
			if err := p.pgClient.UpdateDeltaCheckpointStatus(ctx, p.processId, filepaths, CheckpointStatusCompleted, 0, ""); err != nil {
				fmt.Fprintf(os.Stderr, "Failed to update checkpoint for imported file: %v\n", err)
			}
			cancel()
		}
	}
}

// importBatchDirectory imports all files in a batch directory with a single operation
func (p *BulkProcessor) importBatchDirectory(batchDir string, isAuxFile bool) error {
	ctx, cancel := context.WithTimeout(p.ctx, 60*time.Minute) // Longer timeout for batch imports
	defer cancel()

	// Get S3 directory path
	datePath := time.Now().Format("2006-01-02")
	dirPath := filepath.Join(datePath, p.processId, batchDir)

	// Get S3 directory URL
	dirURL := p.s3Client.GetS3DirURL(dirPath)

	// Generate a unique table name for the external table
	externalTableName := fmt.Sprintf("ext_%s_%s",
		strings.ReplaceAll(p.config.PostgreSQL.Table, ".", "_"),
		batchDir)

	// Get column names from fields
	columnNames := GetColumnNames(p.fields)

	// Load per-import overrides into a private copy. GetLoadConfigFromDB mutates
	// its argument, while the processor's base configuration is shared and
	// immutable after startup.
	loadConfig := p.config
	s3Config, err := p.pgClient.GetLoadConfigFromDB(ctx, &loadConfig)
	if err != nil {
		return errors.Wrap(err, "failed to get loader configuration from database for batch import")
	}
	// Create external table with column names (types will be taken from target table)
	// Note: Using directory URL instead of single file URL
	// Drop external table, becuase we have a retry mechanism in the import process
	err = p.pgClient.DropExternalTable(ctx, externalTableName)
	if err != nil {
		return err
	}

	err = p.pgClient.CreateExternalTable(ctx, dirURL, externalTableName, columnNames, *s3Config)
	if err != nil {
		return err
	}

	// Import data from external table
	err = p.pgClient.ImportFromExternalTable(ctx, externalTableName, columnNames, loadConfig.UpdateOnConflict, isAuxFile)
	if err != nil {
		return err
	}

	// Drop external table
	err = p.pgClient.DropExternalTable(ctx, externalTableName)
	if err != nil {
		return err
	}

	return nil
}

func (p *BulkProcessor) AutoFlushThread() {
	defer p.importerWg.Done()

	for {
		select {
		case <-p.ctx.Done():
			log.Println("AutoFlush thread context canceled, exiting...")
			return
		default:
			// Not canceled
		}
		fileTimeoutDuration := time.Duration(p.config.FileWriteTimeout) * time.Second
		lastFlushTime := p.getLastFlushTime()
		if time.Since(lastFlushTime) >= fileTimeoutDuration {
			Debug("AutoFlush thread doing flush (last flush: %v)", lastFlushTime)
			p.Flush()
		} else {
			timeSleep := fileTimeoutDuration - time.Since(lastFlushTime)
			Debug("AutoFlush thread waiting for autoflush (last flush: %v)", lastFlushTime)
			select {
			case <-p.ctx.Done():
				return
			case <-time.After(timeSleep):
			}
		}
	}
}

func (p *BulkProcessor) BGWorkerThread() {
	defer p.importerWg.Done()

	for {
		select {
		case <-p.ctx.Done():
			log.Println("BGWorker thread context canceled, exiting...")
			return
		default:
			// Not canceled
		}

		// 1. recycle files and buffers. only recycle local files, not s3 files,
		//	- S3 files can be set to automatically clean up.
		//	- Back up local data to prevent data loss caused by local file loss.
		importedFilepaths := p.fileManager.RecycleFiles(false)
		importedFilepaths = append(importedFilepaths, p.bufferManager.RecycleBuffers()...)
		if len(importedFilepaths) > 0 {
			Log("BGWORKER: recycling files, file number: %d", len(importedFilepaths))
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
			if err := p.pgClient.DeleteDeltaCheckpointByProcessIdAndFilepaths(ctx, p.processId, importedFilepaths); err != nil {
				Debug("Failed to delete delta checkpoint for recycled file: %v\n", err)
			}
			// delete completed delta checkpoint 24 hours ago
			err := p.pgClient.DeleteCompletedDeltaCheckpoint(ctx, 24)
			if err != nil {
				Debug("Failed to delete completed delta checkpoint: %v", err)
			}
			cancel()
		}

		// Loader configuration is immutable for a running processor. Mutating the
		// shared Config here raced every import/flush worker; changes take effect
		// when a new processor is constructed.

		// 3. check if the local csv directory files
		dirPath := p.bufferManager.GetLocalCSVDir()
		fullPath := filepath.Join(p.config.LocalFilePrefix, dirPath)
		if _, err := os.Stat(fullPath); os.IsNotExist(err) {
			Debug("BGWORKER: Directory %s does not exist, skipping", fullPath)
		} else {
			files, err := os.ReadDir(fullPath)
			if err != nil {
				Error("Failed to read directory: %v", err)
			} else {
				Log("BGWORKER: Found %d files in %s", len(files), fullPath)
			}
		}

		// Do not age-delete process directories here: they may contain the only
		// recovery artifact for a shard commit whose main checkpoint is pending.
		// Imported/error buffers are removed through status-aware recycling above.

		// 5. periodic registry reconcile, safety net if notifications are lost
		if p.isSharded {
			registryCtx, registryCancel := context.WithTimeout(context.Background(), 5*time.Second)
			if err := p.instanceRouter.RefreshRegistry(registryCtx); err != nil {
				Debug("Failed to refresh instance registry: %v", err)
			}
			registryCancel()
		}

		time.Sleep(time.Duration(p.config.BGWorkerInterval) * time.Second)
	}
}

func (p *BulkProcessor) getFeedbackValues() []string {
	// scan the feedbackKeys map to get all the column values
	// concate the column values with a comma and send it to the import error channel
	var feedbackKeysArray []string
	p.feedbackKeysMutex.Lock()
	for key := range p.feedbackKeys {
		feedbackKeysArray = append(feedbackKeysArray, key)
	}

	// clear the feedbackKeys map
	p.feedbackKeys = make(map[string]bool)
	p.feedbackKeysMutex.Unlock()

	return feedbackKeysArray
}

// add file to pendingBatchFiles
func (p *BulkProcessor) AddFileToPendingBatchFiles(file *File) error {
	// Skip if not in frozen state
	if file.State != FileStateFrozen {
		return errors.New("file is not in frozen state")
	}

	batchDir := file.BatchDir

	// Add to pending batch files
	p.pendingBatchMutex.Lock()
	defer p.pendingBatchMutex.Unlock()
	p.pendingBatchFiles[batchDir]++
	pendingCount := p.pendingBatchFiles[batchDir]

	log.Printf("File %s added to pending batch directory %s, current count: %d", file.S3Key, batchDir, pendingCount)

	// If we have collected all files for this batch, queue the batch for import
	if pendingCount >= p.config.BatchImportSize {
		delete(p.pendingBatchFiles, batchDir) // Clear the counter
		log.Printf("Queuing batch directory for import: %s with %d files", batchDir, pendingCount)
		// Queue the batch for import without stranding shutdown if the queue is full.
		select {
		case p.batchQueue <- batchDir:
			p.setLastFlushTime(time.Now())
		case <-p.ctx.Done():
			return ErrProcessorClosed
		}
	}

	return nil
}

func (p *BulkProcessor) ListenThread() {
	defer p.importerWg.Done()

	listenChannelName := fmt.Sprintf("LISTEN %s", p.GetRoutingChannelName())

	// Create trigger
	if err := p.pgClient.CreateRoutingTableTrigger(p.ctx, p.GetRoutingTableName(), p.GetRoutingChannelName()); err != nil {
		log.Printf("Failed to create trigger: %v", err)
		return
	}

	for {
		select {
		case <-p.ctx.Done():
			log.Println("Listener thread context canceled, exiting...")
			return
		default:
			conn, err := p.pgClient.pool.Acquire(p.ctx)
			if err != nil {
				Debug("Error acquiring connection: %v", err)
				time.Sleep(5 * time.Second)
				continue
			}

			// Start listening for notifications
			_, err = conn.Exec(p.ctx, listenChannelName)
			if err != nil {
				conn.Release()
				Debug("Error listening to routing table changes: %v", err)
				time.Sleep(5 * time.Second)
				continue
			}

			// Continuously listen for notifications
			for {
				select {
				case <-p.ctx.Done():
					conn.Release()
					Log("Listener thread context canceled, exiting...")
					return
				default:
					// Wait for notification
					_, err := conn.Conn().WaitForNotification(p.ctx)
					if err != nil {
						if err == context.Canceled {
							conn.Release()
							Log("Listener thread context canceled, exiting...")
							return
						}
						// Connection error, release current connection and break inner loop to reconnect
						Debug("Listener Connection error, will reconnect: %v", err)
						time.Sleep(1 * time.Second)
						conn.Release()
						goto reconnect
					}

					// Get updated routing table data after receiving notification
					newRoutingHashSet, err := p.pgClient.RefreshRoutingTable(p.ctx, p.GetRoutingTableName())
					if err != nil {
						Debug("Error getting updated routing table: %v", err)
						continue
					}

					// Update routing table using callback function
					p.routingMutex.Lock()
					oldsize := len(p.routingHashSet)
					newsize := len(newRoutingHashSet)
					p.routingHashSet = newRoutingHashSet
					p.routingMutex.Unlock()
					// A full channel already contains an equivalent refresh signal.
					select {
					case p.routingQueue <- true:
					default:
					}
					select {
					case p.routingQueueV2 <- true:
					default:
					}
					Debug("Routing table updated, old size is: %d, new size is: %d, and exec force flush", oldsize, newsize)
					p.Flush()
				}
			}
		}
	reconnect:
		continue
	}
}

// RegistryListenThread listens for changes to relyt_sys.relyt_instance_registry
// and reconciles the InstanceRouter's clients on notify. Runs only in sharded
// mode. Correctness never depends on this: GetClient lazily refreshes on an
// unknown instance, and BGWorkerThread reconciles periodically as a safety net.
// Unlike routing table changes, registry changes never invalidate cached
// routing decisions, so there is no Flush and no routingQueue signal here.
func (p *BulkProcessor) RegistryListenThread() {
	defer p.importerWg.Done()

	listenChannelName := fmt.Sprintf("LISTEN %s", p.GetRegistryChannelName())

	// Concurrent processes race on DROP+CREATE of the shared trigger; the loser
	// gets "already exists", which means the trigger is there, so treat it as
	// success. Retry other errors a few times before degrading to BGWorker
	// reconcile only.
	trigErr := errors.New("registry trigger not created")
	for attempt := range 3 {
		trigErr = p.pgClient.CreateRegistryTrigger(p.ctx, p.GetRegistryChannelName())
		if trigErr == nil || strings.Contains(trigErr.Error(), "already exists") {
			trigErr = nil
			break
		}
		log.Printf("Failed to create registry trigger (attempt %d/3): %v", attempt+1, trigErr)
		time.Sleep(1 * time.Second)
	}
	if trigErr != nil {
		log.Printf("Failed to create registry trigger, registry changes propagate via BGWorker reconcile only: %v", trigErr)
		return
	}

	for {
		if p.ctx.Err() != nil {
			log.Println("Registry listener thread context canceled, exiting...")
			return
		}

		// LISTEN is a session-long operation. Use a dedicated connection rather
		// than consuming a slot from the control-plane query pool.
		connConfig := p.pgClient.pool.Config().ConnConfig.Copy()
		conn, err := pgx.ConnectConfig(p.ctx, connConfig)
		if err != nil {
			Debug("Error opening dedicated registry listener connection: %v", err)
			select {
			case <-p.ctx.Done():
				return
			case <-time.After(5 * time.Second):
				continue
			}
		}
		if _, err = conn.Exec(p.ctx, listenChannelName); err != nil {
			_ = conn.Close(context.Background())
			Debug("Error listening to instance registry changes: %v", err)
			continue
		}

		for {
			_, err = conn.WaitForNotification(p.ctx)
			if err != nil {
				_ = conn.Close(context.Background())
				if p.ctx.Err() != nil {
					Log("Registry listener thread context canceled, exiting...")
					return
				}
				Debug("Registry listener connection error, will reconnect: %v", err)
				break
			}

			// A notification is an explicit dirty signal and must bypass the
			// periodic refresh throttle.
			if _, err := p.instanceRouter.refreshRegistry(p.ctx, true); err != nil {
				Debug("Error refreshing instance registry: %v", err)
				continue
			}
			Debug("Instance registry refreshed on notification")
		}
	}
}

func validateShardedRecordRoutingID(values []string, routingColIndex int, expected string) error {
	if routingColIndex < 0 || routingColIndex >= len(values) {
		return ErrRoutingColumnRequired
	}
	if values[routingColIndex] != expected {
		return errors.Wrapf(ErrRoutingIDMismatch, "got %q, want %q", values[routingColIndex], expected)
	}
	return nil
}

// InsertV2 insert data with dual buffer
func (p *BulkProcessor) InsertV2(fileID, routingID string, records any, offset ...int64) error {
	if p.config.PostgreSQL.Table == "" {
		return ErrPostgreSQLTableRequired
	}

	if !p.config.EnableDualBuffer {
		return errors.New("dual buffer is not enabled")
	}

	p.mutex.RLock()
	if p.isShutdown {
		p.mutex.RUnlock()
		return ErrProcessorClosed
	}
	p.mutex.RUnlock()

	if err := p.ensureStarted(); err != nil {
		return err
	}
	admissionCtx, err := p.beginAdmission()
	if err != nil {
		return err
	}
	defer p.endAdmission()

	// check if data is a slice
	val := reflect.ValueOf(records)
	if val.Kind() == reflect.Pointer {
		val = val.Elem()
	}

	if val.Kind() != reflect.Slice {
		return ErrInvalidInput
	}

	if val.Len() == 0 {
		return ErrEmptyInput
	}

	if err := p.ensureRecordSchema(val); err != nil {
		return err
	}

	// Serialize and validate the entire call before registering the tenant or
	// enqueueing any work. This prevents a bad later record from leaving a
	// permanent mapping or a partially accepted batch.
	recordValues := make([][]string, 0, val.Len())
	for i := 0; i < val.Len(); i++ {
		elemVal := val.Index(i)
		if elemVal.Kind() == reflect.Pointer {
			if elemVal.IsNil() {
				continue
			}
			elemVal = elemVal.Elem()
		}

		values, err := GetFieldValues(elemVal.Interface(), p.fields)
		if err != nil {
			return err
		}
		if p.isSharded {
			if err := validateShardedRecordRoutingID(values, p.routingColIndex, routingID); err != nil {
				return errors.Wrapf(err, "record %d", i)
			}
		}
		recordValues = append(recordValues, values)
	}
	if p.isSharded && len(recordValues) == 0 {
		return ErrEmptyInput
	}

	// Get offset value, default to 0 if not provided
	var recordOffset int64 = 0
	if len(offset) > 0 {
		recordOffset = offset[0]
	}

	// all records in one call share the routingID, resolve the instance once
	instanceID := ""
	if p.isSharded {
		var err error
		instanceID, err = p.instanceRouter.RegisterAndLookup(admissionCtx, routingID)
		if err != nil {
			return err
		}
	}

	for _, values := range recordValues {
		record := &Record{
			Tag:        OperationInsert,
			FileID:     fileID,
			RoutingID:  routingID,
			Values:     values,
			Offset:     recordOffset,
			InstanceID: instanceID,
		}

		if err := p.enqueueRecordV2(admissionCtx, record); err != nil {
			return err
		}
	}

	return nil
}

func (p *BulkProcessor) DeleteSyncV2(fileID, routingID string) error {
	if p.config.PostgreSQL.Table == "" {
		return ErrPostgreSQLTableRequired
	}

	p.mutex.RLock()
	if p.isShutdown {
		p.mutex.RUnlock()
		return ErrProcessorClosed
	}
	p.mutex.RUnlock()

	// In order to solve DeleteSyncV2() failure in server (upgrade etc.),
	// an asynchronous deletion method is added here.The business side needs to ensure:
	// 1. No need to execute DeleteSyncV2() before insert, batch operation will automatically execute deletion.
	// 	Refer to processBufferTaskWithTransaction and guc:DeleteBeforeInsert, otherwise insert first and then delete may cause data loss
	// 2. DeleteSyncV2 will only be called when data is actually deleted. If synchronous deletion fails,
	// 	it will be converted to asynchronous, and the deletion will be successful after the database is restored.
	if p.config.AsyncDelete {
		return p.DeleteV2(fileID, routingID)
	}

	target := p.pgClient
	if p.isSharded {
		instanceID, found, err := p.instanceRouter.LookupInstance(p.ctx, routingID)
		if err != nil {
			Debug("Failed to lookup instance for routingID %s: %v, will retry in async mode", routingID, err)
			return p.DeleteV2(fileID, routingID)
		}
		if !found {
			// no mapping means no data
			return nil
		}
		target, err = p.instanceRouter.GetClient(p.ctx, instanceID)
		if err != nil {
			Debug("Failed to get client for instance %s: %v, will retry in async mode", instanceID, err)
			return p.DeleteV2(fileID, routingID)
		}
	}

	_, err := target.DeleteTablesWithCondition(p.ctx, p.config.PostgreSQL.Schema, p.config.PostgreSQL.Table, fileID, routingID, p.hasRoutingTable)
	if err != nil {
		Debug("Failed to delete file %s with routingID %s sync: %v, will retry in async mode", fileID, routingID, err)
		return p.DeleteV2(fileID, routingID)
	}

	return nil
}

