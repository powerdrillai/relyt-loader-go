// BulkProcessor represents a bulk processor for PostgreSQL
type BulkProcessor struct {
	config            Config
	processId         string // Unique ID for this processor instance
	pgClient          *PostgreSQLClient
	s3Client          *S3Client
	fileManager       *FileManager
	structType        reflect.Type
	fields            []FieldInfo
	schemaMutex       sync.Mutex // initializes and validates reflection metadata atomically
	importerWg        sync.WaitGroup
	admissionWg       sync.WaitGroup // API calls admitted before shutdown publication
	mutex             sync.RWMutex
	ctx               context.Context
	cancel            context.CancelFunc
	isStarted         bool
	flushMutex        sync.RWMutex
	admissionGate     sync.RWMutex // Flush/Shutdown barrier against API admissions
	isShutdown        bool
	fileQueue         chan string    // Queue of file IDs to be imported
	batchQueue        chan string    // Queue of batch directories to be imported
	routingQueue      chan bool      // channel to notify the routing table is updated
	routingQueueV2    chan bool      // channel to notify the routing table is updated
	pendingBatchFiles map[string]int // Map of batch directory to count of pending files
	pendingBatchMutex sync.RWMutex

	recordsQueue chan []string // Channel to write records, support one processor used by multiple goroutines
	recordsNum   atomic.Int32  // Number of records in the recordsQueue
	// this hashmap used to store the column value, return the values to the upper layer
	// when import failed.
	// init: new processor, initialize the map.
	// write: for every insert record, write the specific column value into the map if
	// the value does not existed in the map.
	// read: when import failed, scan the map to get all the column values.
	// clear: finish the import, clear the map.
	feedbackKeys        map[string]bool
	feedbackKeysMutex   sync.RWMutex
	ImportErrorCallback ImportErrorHandler // Callback function to handle import errors
	feedFieldIndex      int
	lastFlushTime       time.Time
	lastFlushMutex      sync.RWMutex
	hasRoutingTable     bool
	routingColIndex     int
	versionColIndex     int
	pkColumns           []string
	pkColumnsIndex      []int
	routingMutex        sync.RWMutex
	routingHashSet      map[string]struct{}
	instanceRouter      *InstanceRouter // nil when the table is not instance-sharded
	isSharded           bool

	bufferManager   *BufferManager
	bufferTaskQueue chan *BufferTask
	bufferThreadWg  sync.WaitGroup
	recordQueueV2   chan *Record
	insertV2Done    chan struct{} // closed when InsertThreadV2 exits; no more bufferTaskQueue sends from it

	// Global offset tracking using atomic variable
	maxOffset atomic.Int64

	// import workers: parallel workers (non-sharded) or per-instance workers (sharded)
	workerWg               sync.WaitGroup
	metadataWg             sync.WaitGroup // asynchronous control-plane checkpoint writes
	activeWorkers          int32          // atomic counter for active workers
	routingTableCache      map[string]routingTableCacheEntry
	routingTableCacheMutex sync.RWMutex
}

// routingTableCacheEntry caches both routing modes for a table with one check time.
type routingTableCacheEntry struct {
	lastCheckTime   time.Time
	hasRoutingTable bool
	isSharded       bool
}

// SearchResult
type SearchResult struct {
	Columns []string // column names
	Rows    [][]any  // data rows
}

// SearchOptions
type SearchOptions struct {
	Table     string   // table name
	Columns   []string // column names, if empty, select all columns. support alias, like "vector <-> $1 as ds"
	Condition string   // query condition, like "id = $1 AND name = $2"
	OrderBy   string   // order by, like "id DESC, name ASC"
	Limit     int      // limit, 0 means no limit
	Offset    int      // offset, for pagination
	GroupBy   string   // group by, like "id, name"
	Having    string   // having, like "id > 100"
	FinalSQL  string   // final sql, generated by the library with the other fields, do not need to set this field
	RoutingID string   // required on instance-sharded tables (routes to the owning instance); ignored otherwise
}

func setTimezone() {
	loc, err := time.LoadLocation("Asia/Shanghai")
	if err != nil {
		log.Printf("Warning: failed to load Asia/Shanghai timezone: %v, using system default", err)
		return
	}
	time.Local = loc
}

// New creates a new BulkProcessor instance
func New(config Config) (*BulkProcessor, error) {
	// Validate config
	if err := config.Validate(); err != nil {
		return nil, err
	}

	setTimezone()
	log.Println("set timezone to Asia/Shanghai")

	SetLogLevel(config.LogLevel)

	// Generate a unique process ID
	processId := uuid.New().String()

	// Create PostgreSQL client first, as we need it to get S3 config
	pgClient, err := NewPostgreSQLClient(config.PostgreSQL)
	if err != nil {
		return nil, err
	}

	// Get S3 config from database
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	// Get S3 config from database
	s3Config, err := pgClient.GetLoadConfigFromDB(ctx, &config)
	if err != nil {
		pgClient.Close()
		return nil, errors.Wrap(err, "failed to get S3 configuration from database")
	}

	// Create S3 client with the appropriate config
	s3Client, err := NewS3Client(*s3Config)
	if err != nil {
		// Make sure to close the PostgreSQL client if S3 client creation fails
		pgClient.Close()
		return nil, err
	}

	// Create file manager
	filePrefix := fmt.Sprintf("relyt_bulk_%s", strings.ReplaceAll(config.PostgreSQL.Table, ".", "_"))
	fileManager := NewFileManager(s3Client, filePrefix, config.BatchSize, processId, config.BatchImportSize)

	// Initialize checkpoint for this process
	pgTable := fmt.Sprintf("%s.%s", config.PostgreSQL.Schema, config.PostgreSQL.Table)
	if err = pgClient.InitializeCheckpoint(ctx, processId, pgTable); err != nil {
		pgClient.Close()
		return nil, errors.Wrap(err, "failed to initialize checkpoint")
	}

	// pg_tables stores fold-to-lowercase names; match it or a mixed-case
	// Table silently detects as non-sharded/non-routed
	lowerTable := strings.ToLower(config.PostgreSQL.Table)
	routingTableName := fmt.Sprintf("%s%s", lowerTable, routingTableSuffix)
	hasRoutingTable, err := pgClient.HasRoutingTable(ctx, routingTableName)
	if err != nil {
		pgClient.Close()
		return nil, errors.Wrap(err, "failed to check if routing table exists")
	}

	instanceRoutingTableName := fmt.Sprintf("%s%s", lowerTable, instanceRoutingTableSuffix)
	isSharded, err := pgClient.HasRoutingTable(ctx, instanceRoutingTableName)
	if err != nil {
		pgClient.Close()
		return nil, errors.Wrap(err, "failed to check if instance routing table exists")
	}

	if hasRoutingTable && isSharded {
		pgClient.Close()
		return nil, ErrBothRoutingTables
	}

	var instanceRouter *InstanceRouter
	if isSharded {
		instanceRouter, err = NewInstanceRouter(pgClient, config.PostgreSQL)
		if err != nil {
			pgClient.Close()
			return nil, errors.Wrap(err, "failed to initialize instance router")
		}
		// the router's initial refresh dials every registry instance and can
		// outlive the early 10s budget; the remaining startup steps (which
		// only need main plus the default instance) get a fresh one
		ctx, cancel = context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		var defaultInstanceID string
		defaultInstanceID, err = instanceRouter.GetDefaultInstanceID(ctx)
		if err != nil {
			instanceRouter.Close()
			pgClient.Close()
			return nil, errors.Wrap(err, "failed to get default instance id")
		}
		if _, err = instanceRouter.GetClient(ctx, defaultInstanceID); err != nil {
			instanceRouter.Close()
			pgClient.Close()
			return nil, errors.Wrap(err, "default instance is unusable")
		}
		// a sentinel pointing at a draining instance must fail at boot, not
		// at first registration
		if status, known := instanceRouter.instanceStatus(defaultInstanceID); !known || status != instanceStatusActive {
			instanceRouter.Close()
			pgClient.Close()
			return nil, errors.Wrapf(ErrNoDefaultInstance,
				"default instance %s has registry status %q, want %q", defaultInstanceID, status, instanceStatusActive)
		}
	}

	// Initialize routing table for this process
	routingHashSet := make(map[string]struct{})
	if hasRoutingTable {
		routingHashSet, err = pgClient.RefreshRoutingTable(ctx, routingTableName)
		Log("Init: routingHashSet size: %d", len(routingHashSet))
		if err != nil {
			pgClient.Close()
			return nil, errors.Wrap(err, "failed to initialize routing table")
		}
	}

	pkColumns, err := pgClient.GetTablePrimaryKeys(ctx)
	if err != nil {
		if instanceRouter != nil {
			instanceRouter.Close()
		}
		pgClient.Close()
		return nil, errors.Wrap(err, "failed to get primary keys")
	}
	if isSharded {
		hasRoutingPK := false
		for _, column := range pkColumns {
			if strings.EqualFold(column, "routing_id") {
				hasRoutingPK = true
				break
			}
		}
		if !hasRoutingPK {
			instanceRouter.Close()
			pgClient.Close()
			return nil, ErrShardedPrimaryKey
		}
	}

	var bufferManager *BufferManager
	if config.EnableDualBuffer {
		bufferManager = NewBufferManager(filePrefix, processId)
	}

	ctx, cancel = context.WithCancel(context.Background())

	return &BulkProcessor{
		config:                 config,
		processId:              processId,
		pgClient:               pgClient,
		s3Client:               s3Client,
		fileManager:            fileManager,
		ctx:                    ctx,
		cancel:                 cancel,
		fileQueue:              make(chan string, 1000), // Buffer for file queue
		batchQueue:             make(chan string, 1000), // Buffer for batch queue
		routingQueue:           make(chan bool, 10),     // Buffer for routing table updated
		routingQueueV2:         make(chan bool, 10),     // Buffer for routing table updated
		pendingBatchFiles:      make(map[string]int),    // Tracks files pending in each batch
		feedbackKeys:           make(map[string]bool),   // Tracks error keys for failed imports
		recordsQueue:           make(chan []string, 10000),
		feedFieldIndex:         -1,
		lastFlushTime:          time.Now(),
		hasRoutingTable:        hasRoutingTable,
		routingColIndex:        -1,
		versionColIndex:        -1,
		routingHashSet:         routingHashSet,
		instanceRouter:         instanceRouter,
		isSharded:              isSharded,
		pkColumns:              pkColumns,
		pkColumnsIndex:         nil,
		bufferManager:          bufferManager,
		bufferTaskQueue:        make(chan *BufferTask, 200),
		bufferThreadWg:         sync.WaitGroup{},
		recordQueueV2:          make(chan *Record, 10000),
		insertV2Done:           make(chan struct{}),
		workerWg:               sync.WaitGroup{},
		activeWorkers:          0,
		routingTableCache:      make(map[string]routingTableCacheEntry),
		routingTableCacheMutex: sync.RWMutex{},
	}, nil
}

